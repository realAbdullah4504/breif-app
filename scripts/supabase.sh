  echo "Repairing migration: $migration"
  npx supabase migration repair --status reverted "$migration"
  if [ $? -eq 0 ]; then
    echo "Successfully marked $migration as reverted"
  else
    echo "Error repairing migration $migration"
    exit 1
  fi
done

